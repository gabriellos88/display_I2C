#ifndef __MAPPING_H__
#define __MAPPING_H__

////////////////////////////////////////////////////////////////////////////////
// application includes
#include "hal/eh008_i2c.h"
#include "hal/eh008.h"
#include "hal/eh008_common.h"

////////////////////////////////////////////////////////////////////////////////
// system includes
#include <stdbool.h>
#include <stdint.h>

////////////////////////////////////////////////////////////////////////////////
// features
#define DISPLAY_COLOR_OFF SSD1306_COLOR_OFF
#define DISPLAY_COLOR_ON SSD1306_COLOR_ON
#define DISPLAY_COLOR_INVERT SSD1306_COLOR_INVERT


////////////////////////////////////////////////////////////////////////////////
// typedefs
typedef ssd1306_color_t display_color_t;

////////////////////////////////////////////////////////////////////////////////
// private functions
//------------------------------------------------------------------------------
static inline void display_init(void)
//------------------------------------------------------------------------------
{
	ssd1306_init();
}

//------------------------------------------------------------------------------
static inline void hw_init(void)
//------------------------------------------------------------------------------
{
	display_init();
}

//------------------------------------------------------------------------------
static inline void display_clear(void)
//------------------------------------------------------------------------------
{
	ssd1306_clear();
}

//------------------------------------------------------------------------------
static inline void display_fill(display_color_t color)
//------------------------------------------------------------------------------
{
	ssd1306_fill(color);
}

//------------------------------------------------------------------------------
static inline void display_update(void)
//------------------------------------------------------------------------------
{
	ssd1306_update();
}

//------------------------------------------------------------------------------
static inline void display_pixel(int16_t x, int16_t y, display_color_t color)
//------------------------------------------------------------------------------
{
	ssd1306_draw_pixel(x, y, color);
}

//------------------------------------------------------------------------------
static inline bool display_pixel_get(int16_t x, int16_t y)
//------------------------------------------------------------------------------
{
	return ssd1306_get_pixel(x, y);
}

//------------------------------------------------------------------------------
static inline void display_line(int16_t x0, int16_t y0, int16_t x1, int16_t y1, display_color_t color)
//------------------------------------------------------------------------------
{
	ssd1306_draw_line(x0, y0, x1, y1, color);
}

//------------------------------------------------------------------------------
static inline void display_rect(int16_t x, int16_t y, int16_t width, int16_t height, display_color_t color)
//------------------------------------------------------------------------------
{
	ssd1306_draw_rect(x, y, width, height, color);
}

#endif // __MAPPING_H__
